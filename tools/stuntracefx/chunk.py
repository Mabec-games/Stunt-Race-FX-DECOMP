#!/usr/bin/env python3
"""chunk.py: cut the long play scripts into short gate scripts.

    chunk.py [FRAMES]       default 500

A play (tools/stuntracefx/plays/NAME.sfx) is a script from power-on that
plays a stretch of the game. Run from power-on in every gate it costs its
whole length each time; most of those frames repeat code other scripts
already run. So each play is flattened (repeat blocks written out) and cut
at command boundaries about every FRAMES frames (a long wait or hold
cut into pieces):

  tools/stuntracefx/states/NAME.sfx    the play with `save NAME_NN` at each
                                       cut (build.py runs it once, making
                                       build/stuntracefx/states/NAME_NN.state)
  tools/stuntracefx/scripts/NAME_NN.sfx
                                       `load` the state at the cut, then the
                                       play's commands up to the next cut

A chunk from its state runs exactly as that stretch of the whole play: the
state is the whole machine. Old chunks of a play are removed first.
Chunks that add no coverage are pruned afterwards (prune.py).
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PLAYS = os.path.join(ROOT, 'tools', 'stuntracefx', 'plays')
RECIPES = os.path.join(ROOT, 'tools', 'stuntracefx', 'states')
SCRIPTS = os.path.join(ROOT, 'tools', 'stuntracefx', 'scripts')
STATE_DIR = 'build/stuntracefx/states'


def flatten(lines):
    """The play's commands with repeat blocks written out; comments dropped."""
    out, i = [], 0
    while i < len(lines):
        w = lines[i].split('#')[0].split()
        if not w:
            i += 1
            continue
        if w[0] == 'repeat':
            depth, k = 0, i + 1
            while True:
                v = lines[k].split('#')[0].split()
                if v and v[0] == 'repeat':
                    depth += 1
                elif v and v[0] == 'end':
                    if depth == 0:
                        break
                    depth -= 1
                k += 1
            body = flatten(lines[i + 1:k])
            out += body * int(w[1])
            i = k + 1
            continue
        # A long wait or hold is written as pieces of at most 500 frames,
        # so a cut can fall inside it: no frame runs between the pieces.
        if w[0] in ('wait', 'hold') and int(w[-1]) > 500:
            n = int(w[-1])
            while n > 0:
                out.append(' '.join(w[:-1] + [str(min(n, 500))]))
                n -= 500
        else:
            out.append(' '.join(w))
        i += 1
    return out


def frames(cmd):
    w = cmd.split()
    if w[0] == 'wait':
        return int(w[1])
    if w[0] == 'hold':
        return int(w[2])
    if w[0] == 'press':
        return (int(w[2]) if len(w) > 2 else 2) + 2
    return 0


def header(path):
    """The play's leading comment lines."""
    h = []
    for l in open(path):
        if not l.startswith('#'):
            break
        h.append(l.rstrip('\n'))
    return h


def main(argv):
    size = int(argv[0]) if argv else 500
    for play in sorted(glob.glob(os.path.join(PLAYS, '*.sfx'))):
        name = os.path.splitext(os.path.basename(play))[0]
        for old in glob.glob(os.path.join(SCRIPTS, name + '_[0-9][0-9].sfx')):
            os.remove(old)
        cmds = flatten(open(play).read().splitlines())
        cuts, t, start = [], 0, 0
        for i, c in enumerate(cmds):
            t += frames(c)
            if t >= size and i + 1 < len(cmds):
                cuts.append((start, i + 1))
                start, t = i + 1, 0
        cuts.append((start, len(cmds)))
        recipe = ['# %s: the play %s, saving a state at each cut its gate' % (name, name),
                  '# scripts (scripts/%s_NN.sfx) start from. Generated by chunk.py.' % name]
        for n, (a, b) in enumerate(cuts):
            recipe.append('save %s_%02d' % (name, n))
            recipe += cmds[a:b]
            chunk = ['# %s_%02d: frames of the play %s from its cut %d (generated by' % (name, n, name, n),
                     '# chunk.py; see plays/%s.sfx).' % name] + \
                    ['load %s/%s_%02d.state' % (STATE_DIR, name, n)] + cmds[a:b]
            with open(os.path.join(SCRIPTS, '%s_%02d.sfx' % (name, n)), 'w') as f:
                f.write('\n'.join(chunk) + '\n')
        with open(os.path.join(RECIPES, name + '.sfx'), 'w') as f:
            f.write('\n'.join(recipe) + '\n')
        print('%-24s %3d chunks' % (name, len(cuts)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
