#!/usr/bin/env python3
"""hybrid.py: build the C decomp as a library the verification harness loads.

    hybrid.py           compile src/stuntracefx into build/stuntracefx/hybrid/libsrfx.dylib

Every `@routine BB:AAAA Name` tag in the C names a routine and its address;
each must have an abi_Name wrapper (the entry contract in code). The build
generates the table that tells the harness which original routine each
wrapper stands for. Outputs are deleted before they are rebuilt.
"""
import csv, glob, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'stuntracefx')
OUT = os.path.join(ROOT, 'build', 'stuntracefx', 'hybrid')
LIB = os.path.join(OUT, 'libsrfx.dylib')


def export_head():
    """The committed C tree at HEAD, so gates measure a commit while the
    working tree keeps changing. Returns (source dir, short revision)."""
    rev = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    tree = os.environ.get('SRFX_GATE_TREE', 'src/stuntracefx').rstrip('/')
    out = os.environ.get('SRFX_GATE_OUT')
    dst = os.path.join(ROOT, 'build', 'stuntracefx', out, 'gate_src') if out else \
        os.path.join(ROOT, 'build', 'stuntracefx', 'gate_src')
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    arc = subprocess.run(['git', 'archive', 'HEAD', tree], capture_output=True, cwd=ROOT).stdout
    subprocess.run(['tar', '-x', '-C', dst], input=arc, check=True)
    return os.path.join(dst, tree), rev
TAG = re.compile(r'@routine\s+([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4})\s+(\w+)')
ALIAS = re.compile(r'@alias\s+([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4})')
SPC = re.compile(r'@spc\s+([0-9A-Fa-f]{4})\b')
USES = re.compile(r'@spcuses\s+([0-9A-Fa-f,\s-]+)')


def main(src=None, lib=None):
    global SRC, LIB
    if src:
        SRC, LIB = src, lib
    os.makedirs(os.path.dirname(LIB), exist_ok=True)
    if os.path.exists(LIB):
        os.remove(LIB)
    files = sorted(glob.glob(os.path.join(SRC, '**', '*.c'), recursive=True))
    rows, bad, spc, uses = [], [], {}, {}
    for f in files:
        text = open(f).read()
        for m in TAG.finditer(text):
            addr = int(m.group(1), 16) << 16 | int(m.group(2), 16)
            name = m.group(3)
            if not re.search(r'\bvoid\s+abi_%s\s*\(\s*void\s*\)' % name, text):
                bad.append('%s: @routine %s has no abi_%s' % (os.path.relpath(f, ROOT), name, name))
            rows.append((addr, name))
            # @spc AAAA: SPC700 code (the tag is the ROM address of its first
            # byte; it runs at APU RAM AAAA).
            sp = SPC.search(text[m.end():text.find('*/', m.end())])
            if sp:
                spc[addr] = int(sp.group(1), 16)
                # @spcuses AAAA-BBBB,...: the APU bytes the C depends on (its
                # code and its callees'), end exclusive; the checks use the C
                # only while they hold these ROM bytes.
                us = USES.search(text[m.end():text.find('*/', m.end())])
                if us:
                    uses[addr] = [tuple(int(x, 16) for x in r.split('-')) for r in re.split(r'[,\s]+', us.group(1).strip()) if '-' in r]
            # @alias BB:AAAA in the header: the same code run from another
            # address (work RAM code the game also runs from its ROM copy):
            # the C is entered there too.
            head = text[m.end():text.find('*/', m.end())]
            for al in ALIAS.finditer(head):
                rows.append((int(al.group(1), 16) << 16 | int(al.group(2), 16), name))
    if bad:
        print('\n'.join(bad)); return 1
    seen = {}
    for a, n in rows:
        if a in seen and seen[a] != n:
            print('two routines at %06X: %s, %s' % (a, seen[a], n)); return 1
        seen[a] = n
    table = os.path.join(os.path.dirname(LIB), 'routines.c')
    cat = os.path.join(ROOT, 'build', 'stuntracefx', 'routines.csv')
    catalog = list(csv.DictReader(open(cat))) if os.path.exists(cat) else []
    # Super FX routines go in a table of their own: the harness runs them
    # when the Super FX, not the S-CPU, reaches them.
    gsu = {int(r['addr'], 16) for r in catalog if r['cpu'] == 'gsu'}
    with open(table, 'w') as t:
        t.write('/* Generated by tools/stuntracefx/hybrid.py. */\n#include <stdint.h>\n')
        for n in sorted({n for a, n in rows}):
            t.write('void abi_%s(void);\n' % n)
        t.write('typedef struct { uint32_t addr; void (*abi)(void); const char *name; } Routine;\n')
        # SPC700 routines too, with their APU address and the APU bytes they
        # depend on, as (APU address, length, ROM offset) runs: from the block
        # list that holds the tag's ROM byte, else the race driver's (the
        # boot upload, resident under the others).
        sys.path.insert(0, os.path.join(ROOT, 'tools', 'stuntracefx'))
        import spcmap
        rom = open(os.path.join(ROOT, 'build', 'stuntracefx', 'baserom.sfc'), 'rb').read()
        lists = spcmap.lists(rom)
        def apu_rom(addr):
            o = spcmap.rom_offset(addr >> 16, addr & 0xFFFF)
            own = next((bl for bl, _ in lists.values() if any(off <= o < off + n for _, n, off in bl)), [])
            m = {}
            for bl in (lists.get('$19:C27C', ([], 0))[0], own):
                for d, n, off in bl:
                    for k in range(n):
                        m[(d + k) & 0xFFFF] = off + k
            return m
        def walk(m, entry):
            """The APU bytes reachable from entry in the code m maps: through
            fall-through, branches, JMP and CALL/PCALL (transitively), up to
            a RET, RETI, a JMP (!a+X) or STOP: what a translated C runs."""
            import spc700
            got, todo = set(), [entry]
            while todo:
                x = todo.pop()
                while x in m and x not in got:
                    op = rom[m[x]]
                    ln = spc700.length(op)
                    if any(((x + k) & 0xFFFF) not in m for k in range(ln)):
                        break
                    for k in range(ln):
                        got.add((x + k) & 0xFFFF)
                    v = spc700.operands(op, bytes(rom[m[(x + k) & 0xFFFF]] for k in range(1, ln)), x)
                    if op in (0x3F, 0x5F):
                        todo.append(v['a'])
                    if op == 0x4F:
                        todo.append(0xFF00 | v['u'])
                    if 'r' in v:
                        todo.append(v['r'])
                    if op in (0x6F, 0x7F, 0x5F, 0x1F, 0xFF, 0xEF, 0x0F):
                        break
                    x = (x + ln) & 0xFFFF
            out, lo = [], None
            for x in sorted(got) + [None]:
                if lo is not None and (x is None or x != prev + 1):
                    out.append((lo, prev + 1)); lo = None
                if x is not None and lo is None:
                    lo = x
                prev = x
            return out
        sel = [x for x in rows if x[0] in spc]
        t.write('typedef struct { uint16_t apu, len; uint32_t rom; } SpcUse;\n')
        for a, n in sel:
            m = apu_rom(a)
            runs = []
            for lo, hi in uses.get(a) or walk(m, spc[a]):
                for x in range(lo, hi):
                    if x not in m:
                        print('@spcuses of %s: APU $%04X is in no uploaded block' % (n, x)); return 1
                    if runs and runs[-1][0] + runs[-1][1] == x and runs[-1][2] + runs[-1][1] == m[x]:
                        runs[-1][1] += 1
                    else:
                        runs.append([x, 1, m[x]])
            t.write('static const SpcUse uses_%s[] = {%s{0, 0, 0}};\n' % (n, ''.join('{0x%04X, %d, 0x%06X}, ' % tuple(r) for r in runs)))
        t.write('typedef struct { uint32_t addr; uint16_t apu; void (*abi)(void); const char *name; const SpcUse *uses; } SpcRoutine;\n')
        t.write('const SpcRoutine sfx_spc_routine_table[] = {\n')
        for a, n in sel:
            t.write('    {0x%06X, 0x%04X, abi_%s, "%s", uses_%s},\n' % (a, spc[a], n, n, n))
        t.write('    {0, 0, 0, 0, 0}\n};\nconst int sfx_spc_routine_count = %d;\n' % len(sel))
        rows = [x for x in rows if x[0] not in spc]
        for var, sel in (('sfx_routine', [x for x in rows if x[0] not in gsu]), ('sfx_gsu_routine', [x for x in rows if x[0] in gsu])):
            t.write('const Routine %s_table[] = {\n' % var)
            for a, n in sel:
                t.write('    {0x%06X, abi_%s, "%s"},\n' % (a, n, n))
            t.write('    {0, 0, 0}\n};\nconst int %s_count = %d;\n' % (var, len(sel)))
        # Every S-CPU routine entry the catalog knows, so the lockstep run can
        # mark where the original enters one inside a swapped call.
        entries = [r['addr'] for r in catalog if r['cpu'] == 'cpu']
        t.write('const uint32_t sfx_catalog[] = {%s0};\nconst int sfx_catalog_count = %d;\n'
                % (''.join('0x%s, ' % a for a in entries), len(entries)))
        # Code the C reaches with call_routine, jump_routine or
        # cpu_loop_forever or cpu_restart that the original enters by a jump (a BRL or
        # JML tail jump, as BigSpritesRow6 to 07:9EE9), not as a
        # catalogued routine: the lockstep run marks those entries too.
        known = {int(a, 16) for a in entries}
        jumps = sorted({int(m, 16) for f in files for m in re.findall(r'(?:call_routine|jump_routine|jump_routine_pushed|cpu_loop_forever|cpu_restart)\(0x([0-9A-Fa-f]{6})', open(f).read())} - known)
        t.write('const uint32_t sfx_jump_entries[] = {%s0};\nconst int sfx_jump_entry_count = %d;\n'
                % (''.join('0x%06X, ' % a for a in jumps), len(jumps)))
        # SPC700 code the C ends at (spc_restart, spc_boot_rom at $FFC0):
        # the checks end a call there.
        sj = sorted({int(m, 16) for f in files for m in re.findall(r'spc_restart\(0x([0-9A-Fa-f]{4})', open(f).read())}
                    | ({0xFFC0} if any('spc_boot_rom()' in open(f).read() for f in files) else set()))
        t.write('const uint16_t sfx_spc_jump_entries[] = {%s0};\nconst int sfx_spc_jump_entry_count = %d;\n'
                % (''.join('0x%04X, ' % a for a in sj), len(sj)))
    cmd = ['cc', '-O2', '-g', '-Wall', '-Wextra', '-std=c99', '-shared', '-fPIC', '-undefined', 'dynamic_lookup',
           '-I', os.path.join(SRC, 'include'), '-o', LIB, table] + files
    p = subprocess.run(cmd, capture_output=True, text=True)
    sys.stdout.write(p.stdout + p.stderr)
    if p.returncode or not os.path.exists(LIB):
        print('hybrid: build failed'); return 1
    print('hybrid: %d routine(s), %d of them SPC700, in %s' % (len({n for a, n in rows}) + len(spc), len(spc), os.path.relpath(LIB, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
