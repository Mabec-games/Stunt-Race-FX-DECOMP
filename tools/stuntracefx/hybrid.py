#!/usr/bin/env python3
"""hybrid.py: build the C decomp as a library the verification harness loads.

    hybrid.py           compile src/stuntracefx into build/stuntracefx/hybrid/libsrfx.dylib

Every `@routine BB:AAAA Name` tag in the C names a routine and its address;
each must have an abi_Name wrapper (the entry contract in code). The build
generates the table that tells the harness which original routine each
wrapper stands for. Outputs are deleted before they are rebuilt.
"""
import csv, glob, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'stuntracefx')
OUT = os.path.join(ROOT, 'build', 'stuntracefx', 'hybrid')
LIB = os.path.join(OUT, 'libsrfx.dylib')


def export_head():
    """The committed C tree at HEAD, so gates measure a commit while the
    working tree keeps changing. Returns (source dir, short revision)."""
    rev = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    dst = os.path.join(ROOT, 'build', 'stuntracefx', 'gate_src')
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    arc = subprocess.run(['git', 'archive', 'HEAD', 'src/stuntracefx'], capture_output=True, cwd=ROOT).stdout
    subprocess.run(['tar', '-x', '-C', dst], input=arc, check=True)
    return os.path.join(dst, 'src', 'stuntracefx'), rev
TAG = re.compile(r'@routine\s+([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4})\s+(\w+)')


def main(src=None, lib=None):
    global SRC, LIB
    if src:
        SRC, LIB = src, lib
    os.makedirs(os.path.dirname(LIB), exist_ok=True)
    if os.path.exists(LIB):
        os.remove(LIB)
    files = sorted(glob.glob(os.path.join(SRC, '**', '*.c'), recursive=True))
    rows, bad = [], []
    for f in files:
        text = open(f).read()
        for m in TAG.finditer(text):
            addr = int(m.group(1), 16) << 16 | int(m.group(2), 16)
            name = m.group(3)
            if not re.search(r'\bvoid\s+abi_%s\s*\(\s*void\s*\)' % name, text):
                bad.append('%s: @routine %s has no abi_%s' % (os.path.relpath(f, ROOT), name, name))
            rows.append((addr, name))
    if bad:
        print('\n'.join(bad)); return 1
    seen = {}
    for a, n in rows:
        if a in seen:
            print('two routines at %06X: %s, %s' % (a, seen[a], n)); return 1
        seen[a] = n
    table = os.path.join(os.path.dirname(LIB), 'routines.c')
    cat = os.path.join(ROOT, 'build', 'stuntracefx', 'routines.csv')
    catalog = list(csv.DictReader(open(cat))) if os.path.exists(cat) else []
    # Super FX routines go in a table of their own: the harness runs them
    # when the Super FX, not the S-CPU, reaches them.
    gsu = {int(r['addr'], 16) for r in catalog if r['cpu'] == 'gsu'}
    with open(table, 'w') as t:
        t.write('/* Generated by tools/stuntracefx/hybrid.py. */\n#include <stdint.h>\n')
        for a, n in rows:
            t.write('void abi_%s(void);\n' % n)
        t.write('typedef struct { uint32_t addr; void (*abi)(void); const char *name; } Routine;\n')
        for var, sel in (('sfx_routine', [x for x in rows if x[0] not in gsu]), ('sfx_gsu_routine', [x for x in rows if x[0] in gsu])):
            t.write('const Routine %s_table[] = {\n' % var)
            for a, n in sel:
                t.write('    {0x%06X, abi_%s, "%s"},\n' % (a, n, n))
            t.write('    {0, 0, 0}\n};\nconst int %s_count = %d;\n' % (var, len(sel)))
        # Every S-CPU routine entry the catalog knows, so the lockstep run can
        # mark where the original enters one inside a swapped call.
        entries = [r['addr'] for r in catalog if r['cpu'] == 'cpu']
        t.write('const uint32_t sfx_catalog[] = {%s0};\nconst int sfx_catalog_count = %d;\n'
                % (''.join('0x%s, ' % a for a in entries), len(entries)))
    cmd = ['cc', '-O2', '-Wall', '-Wextra', '-std=c99', '-shared', '-fPIC', '-undefined', 'dynamic_lookup',
           '-I', os.path.join(SRC, 'include'), '-o', LIB, table] + files
    p = subprocess.run(cmd, capture_output=True, text=True)
    sys.stdout.write(p.stdout + p.stderr)
    if p.returncode or not os.path.exists(LIB):
        print('hybrid: build failed'); return 1
    print('hybrid: %d routine(s) in %s' % (len(rows), os.path.relpath(LIB, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
